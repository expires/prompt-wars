/**
 * Polish (default) and English. Polish sentences keep place names in the nominative ("Cel:
 * Sukiennice") and second person in the present tense, so nothing needs declension or gender.
 */
export type { Lang } from './prefs';
import type { Lang } from './prefs';

export const lang = (): Lang => prefs.current.lang;

export interface PlaceView extends PlaceText {
  /** English only: the Polish name and how to say it */
  polish: string;
  say: string;
}

export function place(l: Landmark): PlaceView {
  if (lang() === 'pl') return { ...PLACES_PL[l.id], polish: '', say: '' };
  return { name: l.name, short: l.short, story: l.story, fact: l.fact, polish: l.polish, say: l.say };
}

export function legend(s: Secret): LegendText {
  if (lang() === 'pl') return LEGENDS_PL[s.id];
  return { name: s.name, hint: s.hint, verb: s.verb, found: s.found };
}

/** "1 metre" / "40 metres"; "1 metr" / "3 metry" / "40 metrów" */
export function metres(n: number): string {
  if (lang() === 'en') return `${n} ${n === 1 ? 'metre' : 'metres'}`;
  const m10 = n % 10;
  const m100 = n % 100;
  const form = n === 1 ? 'metr' : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 'metry' : 'metrów';
  return `${n} ${form}`;
}

const COMPASS = {
  en: ['north', 'north-east', 'east', 'south-east', 'south', 'south-west', 'west', 'north-west'],
  pl: ['północ', 'północny wschód', 'wschód', 'południowy wschód', 'południe', 'południowy zachód', 'zachód', 'północny zachód'],
};
/** compass point for a bearing in degrees */
export const compassWord = (bearing: number) => COMPASS[lang()][Math.round(bearing / 45) % 8];

const CLOCK_PL = ['', 'pierwszej', 'drugiej', 'trzeciej', 'czwartej', 'piątej', 'szóstej', 'siódmej', 'ósmej', 'dziewiątej', 'dziesiątej', 'jedenastej', 'dwunastej'];

/** direction words for an angle in radians (positive = right); `clock` adds the clock position */
export function relativeWords(rel: number, clock = true): string {
  const deg = (rel * 180) / Math.PI;
  const a = Math.abs(deg);
  const right = deg > 0;
  const hour = ((Math.round(deg / 30) % 12) + 12) % 12 || 12;
  if (lang() === 'pl') {
    const side = right ? 'prawej' : 'lewej';
    const words = a < 15 ? 'prosto przed tobą' : a < 55 ? `z przodu po ${side}` : a < 125 ? `po ${side}` : a < 165 ? `z tyłu po ${side}` : 'za tobą';
    return clock ? `${words}, na godzinie ${CLOCK_PL[hour]}` : words;
  }
  const side = right ? 'right' : 'left';
  const words = a < 15 ? 'straight ahead' : a < 55 ? `ahead to your ${side}` : a < 125 ? `to your ${side}` : a < 165 ? `behind you to the ${side}` : 'behind you';
  return clock ? `${words}, at ${hour} o’clock` : words;
}

